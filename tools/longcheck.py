SETTLE = 600
TRACK = 120
SEEDS = (0, 1, 2)

def main():
    print(f"Evaluating {len(CANDS)} stages across {len(SEEDS)} seeds (settle={SETTLE}, track={TRACK})...")
    for name, visc, radius, counts, matrix in CANDS:
        rules = np.array([float(v) for v in matrix.split()],
                         dtype=np.float32).reshape(6, 6)
        per_seed = []
        for seed in SEEDS:
            result = sc.simulate(rules, visc, counts, radius, SETTLE, TRACK, seed)
            per_seed.append(None if result is None else result[0])
        if any(r is None for r in per_seed):
            print(f"{name:10s}: UNSTABLE in long run")
            continue
        keys = ("num_blobs", "largest_frac", "frac_clustered", "mix", "aspect",
                "abs_omega", "spin", "shell", "cluster_move", "mean_speed")
        avg = {k: float(np.mean([r[k] for r in per_seed])) for k in keys}
        print(f"{name:10s}: blobs={avg['num_blobs']:4.1f} largest={avg['largest_frac']:.2f} "
              f"cluster={avg['frac_clustered']:.2f} mix={avg['mix']:.2f} "
              f"aspect={avg['aspect']:.2f} spin={avg['spin']:.2f} "
              f"shell={avg['shell']:.2f} move={avg['cluster_move']:.3f}R "
              f"speed={avg['mean_speed']:5.2f}")
    print("All stages verified.")

if __name__ == "__main__":
    main()
